/* Syntax of Switch Statement 

switch (key) {
    case value:
        
        break;

    default:
        break;
}

*/

const month = 3;

switch (month) {
    case 1:
        console.log("january")
        break;
    case 2:
        console.log("Febuary")
        break;
    case 3:
        console.log("March")
        break;
    case 4:
        console.log("May")
        break;
    case 5:
        console.log("June")
        break;
    case 6:
        console.log("july")
        break;


    default:
        console.log("Nothing")
        break;
}

